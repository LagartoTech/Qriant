private val Ink = Color(0xFF101318)
private val Panel = Color(0xFF1A2028)
private val Accent = Color(0xFF9BE7C4)
private val Muted = Color(0xFF9AA6B2)

class MainActivity : ComponentActivity() {
    override fun onCreate(savedInstanceState: Bundle?) {
        super.onCreate(savedInstanceState)
        setContent { QriantApp() }
    }
}

@Composable
private fun QriantApp() {
    var tab by remember { mutableStateOf(0) }
    var generated by remember { mutableStateOf<Bitmap?>(null) }
    var input by remember { mutableStateOf("https://example.com") }
    var scanned by remember { mutableStateOf<ScannedCode?>(null) }
    var imageStatus by remember { mutableStateOf("") }
    val context = LocalContext.current
    var cameraGranted by remember {
        mutableStateOf(ContextCompat.checkSelfPermission(
            context, Manifest.permission.CAMERA
        ) == PackageManager.PERMISSION_GRANTED)
    }
    val permissionLauncher = rememberLauncherForActivityResult(
        ActivityResultContracts.RequestPermission()
    ) { cameraGranted = it }

    val storagePermissionLauncher = rememberLauncherForActivityResult(
        ActivityResultContracts.RequestPermission()
    ) { granted ->
        if (granted) {
            generated?.let { bitmap ->
                imageStatus = if (saveQrToGallery(context, bitmap)) {
                    "Saved to Pictures/Qriant"
                } else {
                    "Could not save image"
                }
            }
        } else {
            imageStatus = "Storage permission denied"
        }
    }

    MaterialTheme(
        colorScheme = darkColorScheme(
            background = Ink, surface = Panel, primary = Accent,
            onPrimary = Ink, onBackground = Color.White,
            onSurface = Color.White, secondary = Muted
        )
    ) {
        Scaffold(
            containerColor = Ink,
            topBar = {
                Column(Modifier.fillMaxWidth().padding(horizontal = 22.dp, vertical = 18.dp)) {
                    Text("LAGARTOTECH  /  UTILITIES", color = Accent, style = MaterialTheme.typography.labelSmall)
                    Spacer(Modifier.height(7.dp))
                    Text("Qriant", style = MaterialTheme.typography.headlineLarge, fontWeight = FontWeight.Bold)
                    Text("Scan codes. Create QR.", color = Muted, style = MaterialTheme.typography.bodyMedium)
                }
            },
            bottomBar = {
                NavigationBar(containerColor = Panel) {
                    NavigationBarItem(
                        selected = tab == 0, onClick = { tab = 0 },
                        icon = { Icon(Icons.Default.CenterFocusStrong, null) },
                        label = { Text("Scan") }
                    )
                    NavigationBarItem(
                        selected = tab == 1, onClick = { tab = 1 },
                        icon = { Icon(Icons.Default.QrCode, null) },
                        label = { Text("Create") }
                    )
                }
            }
        ) { padding ->
            if (tab == 0) {
                Column(Modifier.fillMaxSize().padding(padding).padding(20.dp)) {
                    Text("SCANNER", color = Accent, style = MaterialTheme.typography.labelMedium)
                    Spacer(Modifier.height(12.dp))
                    if (cameraGranted) {
                        CameraScanner(
                            modifier = Modifier.fillMaxWidth().weight(1f),
                            onResult = { scanned = it }
                        )
                    } else {
                        Box(
                            Modifier.fillMaxWidth().weight(1f)
                                .background(Panel, RoundedCornerShape(22.dp)).padding(24.dp),
                            contentAlignment = Alignment.Center
                        ) {
                            Column(horizontalAlignment = Alignment.CenterHorizontally) {
                                Icon(Icons.Default.CenterFocusStrong, null, tint = Accent, modifier = Modifier.size(42.dp))
                                Spacer(Modifier.height(12.dp))
                                Text("Camera permission is needed to scan codes.", color = Color.White)
                                Spacer(Modifier.height(14.dp))
                                Button(onClick = { permissionLauncher.launch(Manifest.permission.CAMERA) }) {
                                    Text("Allow camera")
                                }
                            }
                        }
                    }
                    Spacer(Modifier.height(12.dp))
                    GalleryQrPicker(onResult = { scanned = it })

                    scanned?.let { result ->
                        Spacer(Modifier.height(14.dp))
                        ResultCard(result.value, result.format)
                    }
                }
            } else {
                Column(
                    Modifier.fillMaxSize().padding(padding).padding(horizontal = 20.dp)
                        .verticalScroll(rememberScrollState())
                ) {
                    Text("CREATE A CODE", color = Accent, style = MaterialTheme.typography.labelMedium)
                    Spacer(Modifier.height(12.dp))
                    Text("Content", color = Muted)
                    Spacer(Modifier.height(8.dp))
                    OutlinedTextField(
                        value = input, onValueChange = { input = it },
                        modifier = Modifier.fillMaxWidth(),
                        minLines = 3,
                        placeholder = { Text("Type a link or any text") },
                        colors = OutlinedTextFieldDefaults.colors(
                            focusedBorderColor = Accent,
                            unfocusedBorderColor = Muted,
                            focusedTextColor = Color.White,
                            unfocusedTextColor = Color.White
                        )
                    )
                    Spacer(Modifier.height(14.dp))
                    Button(
                        onClick = { generated = QrGenerator.create(input) },
                        enabled = input.isNotBlank(),
                        modifier = Modifier.fillMaxWidth()
                    ) { Text("Generate QR code") }
                    generated?.let { bitmap ->
                        Spacer(Modifier.height(22.dp))
                        Card(colors = CardDefaults.cardColors(containerColor = Panel)) {
                            Column(
                                Modifier.fillMaxWidth().padding(20.dp),
                                horizontalAlignment = Alignment.CenterHorizontally
                            ) {
                                Image(bitmap.asImageBitmap(), null, modifier = Modifier.size(230.dp))
                                Spacer(Modifier.height(10.dp))
                                Text("PNG image • 720 × 720", color = Muted)
                                Spacer(Modifier.height(16.dp))

                                Row(
                                    modifier = Modifier.fillMaxWidth(),
                                    horizontalArrangement = Arrangement.spacedBy(8.dp)
                                ) {
                                    Button(
                                        onClick = {
                                            if (
                                                Build.VERSION.SDK_INT < Build.VERSION_CODES.Q &&
                                                ContextCompat.checkSelfPermission(
                                                    context,
                                                    Manifest.permission.WRITE_EXTERNAL_STORAGE
                                                ) != PackageManager.PERMISSION_GRANTED
                                            ) {
                                                storagePermissionLauncher.launch(
                                                    Manifest.permission.WRITE_EXTERNAL_STORAGE
                                                )
                                            } else {
                                                imageStatus = if (saveQrToGallery(context, bitmap)) {
                                                    "Saved to Pictures/Qriant"
                                                } else {
                                                    "Could not save image"
                                                }
                                            }
                                        },
                                        modifier = Modifier.weight(1f)
                                    ) {
                                        Icon(Icons.Default.SaveAlt, null)
                                        Spacer(Modifier.width(5.dp))
                                        Text("Save PNG")
                                    }

                                    OutlinedButton(
                                        onClick = {
                                            try {
                                                shareQrImage(context, bitmap)
                                                imageStatus = "Choose an app to share the QR"
                                            } catch (_: Exception) {
                                                imageStatus = "Could not share image"
                                            }
                                        },
                                        modifier = Modifier.weight(1f)
                                    ) {
                                        Icon(Icons.Default.Share, null)
                                        Spacer(Modifier.width(5.dp))
                                        Text("Share")
                                    }
                                }

                                val clipboard = LocalClipboardManager.current
                                TextButton(
                                    onClick = {
                                        clipboard.setText(AnnotatedString(input))
                                        imageStatus = "Content copied"
                                    }
                                ) {
                                    Icon(Icons.Default.ContentCopy, null)
                                    Spacer(Modifier.width(6.dp))
                                    Text("Copy content")
                                }

                                if (imageStatus.isNotBlank()) {
                                    Text(imageStatus, color = Accent, style = MaterialTheme.typography.bodySmall)
                                }
                            }
                        }
                    }
                    Spacer(Modifier.height(28.dp))
                    Text("Qriant creates codes locally. No account, ads, analytics or network permission.", color = Muted, style = MaterialTheme.typography.bodySmall)
                }
            }
        }
    }
}

@Composable
private fun ResultCard(value: String, format: Int) {
    val clipboard = LocalClipboardManager.current
    val context = LocalContext.current
    val uri = Uri.parse(value)
    val isWebLink = (uri.scheme == "http" || uri.scheme == "https") &&
        !uri.host.isNullOrBlank()

    Card(colors = CardDefaults.cardColors(containerColor = Panel)) {
        Column(Modifier.fillMaxWidth().padding(16.dp)) {
            Text("SCAN RESULT  •  ${barcodeFormatName(format)}", color = Accent, style = MaterialTheme.typography.labelSmall)
            Spacer(Modifier.height(6.dp))
            Text(value, color = Color.White)
            Spacer(Modifier.height(8.dp))
            Row(horizontalArrangement = Arrangement.spacedBy(8.dp)) {
                TextButton(onClick = { clipboard.setText(AnnotatedString(value)) }) {
                    Icon(Icons.Default.ContentCopy, null)
                    Spacer(Modifier.width(6.dp))
                    Text("Copy")
                }
                if (isWebLink) {
                    TextButton(onClick = {
                        try {
                            context.startActivity(Intent(Intent.ACTION_VIEW, uri))
                        } catch (_: Exception) {
                        }
                    }) {
                        Text("Open link")
                    }
                }
            }
        }
    }
}
